using Microsoft.EntityFrameworkCore;
using Restaurant_API.Constants;
using Restaurant_API.Data.Entities;
using Restaurant_API.Data.Entities.Enums;
using Restaurant_API.Data.Mappers;
using Restaurant_API.Data.Models.Other;
using Restaurant_API.Data.Models.Reservation;
using Restaurant_API.Data.Models.Reservation.Enums;
using Restaurant_API.Exceptions;
using Restaurant_API.Repositories.Interfaces;
using Restaurant_API.Services.Interfaces;

namespace Restaurant_API.Services
{
    public class ReservationService : IReservationService
    {
        private readonly IRoleService roleService;
        private readonly IRestaurantService restaurantService;

        private readonly IReservationRepo reservationRepo;

        public ReservationService(IRoleService roleService, IRestaurantService restaurantService, IReservationRepo reservationRepo)
        {
            this.roleService = roleService;
            this.restaurantService = restaurantService;
            this.reservationRepo = reservationRepo;
		}

        public async Task CreateClientReservationAsync(ClientCreateReservationModel createModel)
        {
            // Id is generated by the database
            Reservation r = createModel.ToEntity();
            r.Comment = string.IsNullOrWhiteSpace(r.Comment) ? null : r.Comment;  // If comment is empty -> null

            // Validate that the associated restaurant exists
            if (!await restaurantService.RestaurantExistsAsync(r.RestaurantId))
            {
                throw new NotFoundException(ErrorCodes.Restaurant.NotFound);
            }

            // Validate reservation start time (must not be in the past)
            if (r.StartTimeUtc < DateTime.UtcNow)
            {
                throw new BadRequestException(ErrorCodes.Data.InvalidDate);
            }

            // TODO: Check if the datе is open for reservations

            // Reservation needs to be confirmed by the restaurant
            r.State = ReservationState.Pending;

            // Persist reservation
            await reservationRepo.AddAsync(r);
        }

        public async Task CreateConfirmedReservationAsync(HttpContext ctx, ReservationCreateModel createModel)
        {
            Restaurant currUserRestaurant = await restaurantService.GetCurrUserAssociatedRestaurantAsync(ctx);

            Reservation r = createModel.ToEntity();
            r.RestaurantId = currUserRestaurant.Id;
            r.Comment = string.IsNullOrWhiteSpace(r.Comment) ? null : r.Comment;  // If comment is empty -> null

            // Disallow creating a reservation to a past moment unless the user has the Admin role.
            if (r.StartTimeUtc < DateTime.UtcNow && !roleService.HasCurrUserRole(ctx, Roles.Admin))
            {
                throw new ForbiddenException(ErrorCodes.Reservation.CannotCreateInPast);
            }

            // TODO: Check if the datе is open for reservations

            // Reservation created by a restaurant member is automatically confirmed
            r.State = ReservationState.Confirmed;
            r.IsCreatedByStaff = true;

            // Persist reservation
            await reservationRepo.AddAsync(r);
        }

        public async Task<ReservationViewModel> GetByIdAsync(HttpContext ctx, Guid reservationId)
        {
            // Retrieve the reservation and ensure it belongs to the current user's restaurant
            Reservation reservation = await GetReservationIfOwnedAsync(ctx, reservationId);

            // Convert the reservation entity to a view model
            return reservation.ToView();
        }

        public async Task<ReservationViewModel> UpdateAsync(HttpContext ctx, Guid reservationId, ReservationUpdateModel updateModel)
        {
            // Retrieve the reservation and ensure it belongs to the current user's restaurant
            Reservation reservation = await GetReservationIfOwnedAsync(ctx, reservationId);

            // Track whether any field was actually modified
            bool isModified = false;

            // If the reservation was originally created by a client, core contact details (name, email, phone) cannot be modified
            if (!reservation.IsCreatedByStaff &&
                (updateModel.Name != null || updateModel.Email != null || updateModel.Phone != null))
            {
                throw new ForbiddenException(ErrorCodes.Reservation.CannotModifyClientDetails);
            }

            // Apply name update
            if (!string.IsNullOrEmpty(updateModel.Name) && reservation.Name != updateModel.Name)
            {
                reservation.Name = updateModel.Name;
                isModified = true;
            }

            // Apply email update (passed model validation)
            if (updateModel.Email != null && reservation.Email != updateModel.Email)
            {
                reservation.Email = updateModel.Email;
                isModified = true;
            }

            // Apply phone number update (passed model validation)
            if (updateModel.Phone != null && reservation.Phone != updateModel.Phone)
            {
                reservation.Phone = updateModel.Phone;
                isModified = true;
            }

            // Apply StartTimeUtc update
            if (updateModel.StartTimeUtc.HasValue && reservation.StartTimeUtc != updateModel.StartTimeUtc.Value)
            {
                // Disallow moving a reservation to a past date unless the user has the Admin role.
                if (updateModel.StartTimeUtc.Value < DateTime.UtcNow && !roleService.HasCurrUserRole(ctx, Roles.Admin))
                {
                    throw new ForbiddenException(ErrorCodes.Reservation.CannotModifyToPast);
                }

                reservation.StartTimeUtc = updateModel.StartTimeUtc.Value;
                isModified = true;
            }

            // Apply people count update
            if (updateModel.PeopleCount.HasValue && reservation.PeopleCount != updateModel.PeopleCount.Value)
            {
                reservation.PeopleCount = updateModel.PeopleCount.Value;
                isModified = true;
            }

            // Apply comment update - treat empty or whitespace-only comments as null (i.e., remove the comment)
            if (updateModel.Comment != null)
            {
                var sanitizedComment = string.IsNullOrWhiteSpace(updateModel.Comment) ? null : updateModel.Comment;

                if (reservation.Comment != sanitizedComment)
                {
                    reservation.Comment = sanitizedComment;
                    isModified = true;
                }
            }

            // Persist changes if needed
            if (isModified)
            {
                await reservationRepo.UpdateAsync(reservation);
            }

            // Return the updated reservation to the client
            return reservation.ToView();
        }

        public async Task<Dictionary<DateOnly, List<ReservationCalendarPreviewModel>>> GetConfirmedReservationsInPeriodAsync(HttpContext ctx, DateOnly start, DateOnly end)
        {
            Restaurant currUserRestaurant = await restaurantService.GetCurrUserAssociatedRestaurantAsync(ctx);

            // Ensure 'start' date is before 'end' date
            if (start > end)
            {
                (start, end) = (end, start);
            }

            // Get TimeZoneInfo object for the restaurant's timezone
            TimeZoneInfo restaurantTimeZone = restaurantService.GetTimeZoneInfo(currUserRestaurant);

            // Convert the local 'start' DateOnly to its UTC DateTime equivalent (beginning of the day in restaurant's timezone)
            DateTime periodStartLocal = start.ToDateTime(new TimeOnly(0, 0, 0), DateTimeKind.Unspecified);
            DateTime periodStartUtc = TimeZoneInfo.ConvertTimeToUtc(periodStartLocal, restaurantTimeZone);

            // Convert the local 'end' DateOnly to its UTC DateTime equivalent (beginning of the *next* day in restaurant's timezone)
            // This ensures the entire 'end' day is included in the query range.
            DateTime nextDayAfterPeriodEndLocal = end.AddDays(1).ToDateTime(new TimeOnly(0, 0, 0), DateTimeKind.Unspecified);
            DateTime nextDayAfterPeriodEndUtc = TimeZoneInfo.ConvertTimeToUtc(nextDayAfterPeriodEndLocal, restaurantTimeZone);

            // Fetch confirmed reservations for the restaurant within the calculated UTC date range
            List<Reservation> reservations = await reservationRepo.GetConfirmedInPeriodAsync(currUserRestaurant.Id, periodStartUtc, nextDayAfterPeriodEndUtc);

            // Group reservations by their local date and order by their local time
            var groupedReservations = reservations
                // Group by the local calendar date of the reservation
                .GroupBy(r => DateOnly.FromDateTime(TimeZoneInfo.ConvertTimeFromUtc(r.StartTimeUtc, restaurantTimeZone)))
                .ToDictionary(
                    g => g.Key,
                    // Order reservations within each group by their local time and map to preview models
                    g => g.OrderBy(r => TimeOnly.FromDateTime(TimeZoneInfo.ConvertTimeFromUtc(r.StartTimeUtc, restaurantTimeZone)))
                            .Select(r => r.ToCalendarPreview(restaurantTimeZone))
                            .ToList()
                );

            return groupedReservations;
        }

        public async Task<PagedResult<PendingReservationPreviewModel>> GetPendingReservationsAsync(HttpContext ctx, PendingReservationsQueryParams queryParams)
        {
            Restaurant currUserRestaurant = await restaurantService.GetCurrUserAssociatedRestaurantAsync(ctx);

            // At this point, the query is defined but not yet executed against the database
            IQueryable<Reservation> query = reservationRepo.GetPendingReservationsBaseQuery(currUserRestaurant.Id);

            // Apply sorting [Sort by creation time]
            query = queryParams.SortOrder == SortOrder.Asc
                    ? query.OrderBy(r => r.CreatedAtUtc) // (oldest first)
                    : query.OrderByDescending(r => r.CreatedAtUtc); // (newest first)


            int totalItems = await query.CountAsync();
            int totalPages = (int)Math.Ceiling((double)totalItems / queryParams.Limit);

            // Ensuring only the necessary records for the current page are retrieved from the database
            List<Reservation> paginatedReservations = await query
                    .Skip((queryParams.Page - 1) * queryParams.Limit) // Skips records from previous pages
                    .Take(queryParams.Limit) // Takes only the specified number of records for the current page
                    .ToListAsync();

            List<PendingReservationPreviewModel> previewModels = paginatedReservations
                    .Select(r => r.ToPendingPreview())
                    .ToList();

            return new PagedResult<PendingReservationPreviewModel>
            {
                Items = previewModels,
                Pagination = new PaginationMetadata
                {
                    CurrentPage = queryParams.Page,
                    PageSize = queryParams.Limit,
                    TotalItems = totalItems,
                    TotalPages = totalPages
                }
            };
        }

        // ================================================== Private methods
        private async Task<Reservation> GetReservationIfOwnedAsync(HttpContext ctx, Guid reservationId)
        {
            Restaurant currUserRestaurant = await restaurantService.GetCurrUserAssociatedRestaurantAsync(ctx);

            // Get reservation by id
            Reservation reservation = await reservationRepo.GetByIdAsync(reservationId) ??
                                            throw new NotFoundException(ErrorCodes.Reservation.NotFound);

            // Validate that the user has access to that reservation
            if (reservation.RestaurantId != currUserRestaurant.Id)
            {
                throw new ForbiddenException();
            }

            return reservation;
        }
    }
}
